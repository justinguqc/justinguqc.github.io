const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');
const vscode = require('vscode');

exports.run = async () => {
  const checks = [];
  const report = path.join(__dirname, '..', '.runtime', 'integration-report.json');
  try {
    const extension = vscode.extensions.getExtension('aitrace-lab.aitrace-prototype');
    assert(extension, 'Development extension is discoverable');
    const api = await extension.activate();
    await vscode.commands.executeCommand('aitrace.start', 'todo');
    assert.equal(api.snapshot().total, 3); checks.push('Start prepared case');
    const document = await vscode.workspace.openTextDocument(vscode.Uri.parse(api.snapshot().workingUri));
    assert.equal(document.languageId, 'python');
    assert.equal(document.uri.scheme, 'file');
    assert.match(document.fileName, /pending_tasks\.py$/);
    assert.match(document.getText(), /pending = tasks/);
    checks.push('Main review is an actual Python source file, not a virtual diff');
    assert.equal(api.snapshot().stage, 'original');
    const originalText = document.getText();
    const startLenses = await vscode.commands.executeCommand('vscode.executeCodeLensProvider', document.uri);
    assert.equal(startLenses.length, 1);
    assert.equal(startLenses[0].command.command, 'aitrace.request');
    checks.push('Original code appears with a simulate-AI-output entry');
    await vscode.commands.executeCommand('aitrace.explain');
    assert.equal(api.snapshot().stage, 'original');
    await vscode.commands.executeCommand('aitrace.request');
    assert.equal(api.snapshot().stage, 'review');
    assert.equal(document.getText(), originalText);
    checks.push('Simulate AI output loads prepared suggestions without any prompt input or source overwrite');
    const lenses = await vscode.commands.executeCommand('vscode.executeCodeLensProvider', document.uri);
    assert.equal(lenses.length, 4); checks.push('One branded review banner and one review entry per change; no duplicate decision buttons');
    const firstLens = lenses.find(item => item.command.arguments?.[0] === 'pending-filter');
    const hovers = await vscode.commands.executeCommand('vscode.executeHoverProvider', document.uri, firstLens.range.start);
    assert(hovers.length > 0);
    const markdown = hovers.flatMap(item => item.contents).map(item => item.value || '').join('\n');
    assert.match(markdown, /command:aitrace.explain/);
    checks.push('Native hover links into the dedicated AITrace panel');
    await vscode.commands.executeCommand('aitrace.explain', 'pending-filter');
    assert.equal(api.snapshot().selected, 'pending-filter');
    assert.equal(api.panelState().open, true);
    assert.equal(api.panelState().model.change.id, 'pending-filter');
    const source = await vscode.window.showTextDocument(document, vscode.ViewColumn.One);
    const count = lenses.find(item => item.command.arguments?.[0] === 'pending-count');
    source.selection = new vscode.Selection(count.range.start, count.range.start);
    await new Promise(resolve => setTimeout(resolve, 100));
    assert.equal(api.panelState().model.change.id, 'pending-count');
    await vscode.commands.executeCommand('aitrace.pin');
    const sort = lenses.find(item => item.command.arguments?.[0] === 'sort-tasks');
    source.selection = new vscode.Selection(sort.range.start, sort.range.start);
    await new Promise(resolve => setTimeout(resolve, 100));
    assert.equal(api.panelState().model.change.id, 'pending-count');
    assert.equal(api.panelState().model.pinned, true);
    await vscode.commands.executeCommand('aitrace.pin');
    assert.equal(api.panelState().model.change.id, 'sort-tasks');
    await vscode.commands.executeCommand('aitrace.locate', 'pending-filter');
    assert.equal(source.selection.start.line, firstLens.range.start.line);
    checks.push('Panel follows source selections, can pin/unpin, and locates matching code');
    const undecided = { ...api.snapshot().states };
    await vscode.commands.executeCommand('aitrace.close', 'pending-filter');
    assert.equal(api.panelState().open, false);
    assert.deepEqual(api.snapshot().states, undecided);
    assert.equal(document.getText(), originalText);
    checks.push('Close explanation leaves code and review decisions unchanged');
    await vscode.commands.executeCommand('aitrace.more', 'pending-filter', 'example');
    assert.equal(api.panelState().model.expanded, 'example');
    assert.match(api.panelState().model.change.example, /Read notes \(False\)/);
    checks.push('Follow-up example appears for the matching change');
    await vscode.commands.executeCommand('aitrace.accept', 'pending-filter');
    const moved = await vscode.commands.executeCommand('vscode.executeCodeLensProvider', document.uri);
    const countLens = moved.find(item => item.command.arguments?.[0] === 'pending-count');
    assert.equal(document.lineAt(countLens.range.start.line).text, 'remaining = len(tasks)');
    const disk = Buffer.from(await vscode.workspace.fs.readFile(document.uri)).toString('utf8');
    assert.match(disk, /pending = \[\n/);
    assert.doesNotMatch(disk, /pending = tasks/);
    checks.push('Accept edits and saves the source file; later change anchors move after multiline edits');
    await vscode.commands.executeCommand('aitrace.accept', 'pending-count');
    await vscode.commands.executeCommand('aitrace.reject', 'sort-tasks');
    assert.equal(api.snapshot().reviewed, 3);
    const result = await vscode.commands.executeCommand('aitrace.result');
    assert.match(result, /len\(pending\)/); assert.doesNotMatch(result, /sorted\(/);
    assert.equal(result, document.getText());
    checks.push('Accepted changes update source; rejected suggestion stays out');
    await vscode.commands.executeCommand('aitrace.undo');
    assert.equal(api.snapshot().states['sort-tasks'], 'pending'); checks.push('Undo restores the prior decision state');
    await vscode.commands.executeCommand('aitrace.next', 'pending-filter');
    assert.equal(api.snapshot().selected, 'pending-count');
    await vscode.commands.executeCommand('aitrace.previous', 'pending-count');
    assert.equal(api.snapshot().selected, 'pending-filter'); checks.push('Previous / Next navigation');
    await vscode.commands.executeCommand('aitrace.compare'); checks.push('Native original/suggested diff opens');
    await vscode.commands.executeCommand('aitrace.reset', true);
    assert.equal(api.snapshot().reviewed, 0);
    const reset = await vscode.commands.executeCommand('aitrace.result');
    assert.match(reset, /pending = tasks/); checks.push('Reset restores the original result');
    await vscode.commands.executeCommand('aitrace.start', 'practice');
    await vscode.commands.executeCommand('aitrace.request');
    await vscode.commands.executeCommand('aitrace.accept', 'pass-check');
    const practice = await vscode.commands.executeCommand('aitrace.result');
    assert.match(practice, /score >= 60/); checks.push('Switch cases and include the score=60 boundary');
    await vscode.commands.executeCommand('aitrace.undo');
    const undone = await vscode.commands.executeCommand('aitrace.result');
    assert.match(undone, /return "Not checked"/);
    const realDoc = await vscode.workspace.openTextDocument(vscode.Uri.parse(api.snapshot().workingUri));
    const edit = new vscode.WorkspaceEdit();
    edit.insert(realDoc.uri, new vscode.Position(0, 0), '# My own edit\n');
    await vscode.workspace.applyEdit(edit);
    await new Promise(resolve => setTimeout(resolve, 100));
    assert.equal(api.snapshot().paused, true);
    await vscode.commands.executeCommand('aitrace.accept', 'pass-check');
    assert.match(realDoc.getText(), /# My own edit/);
    assert.match(realDoc.getText(), /return "Not checked"/);
    checks.push('Manual source edits are kept and prevent prepared suggestions from overwriting them');
    await vscode.commands.executeCommand('aitrace.reset', true);
    const titleActions = extension.packageJSON.contributes.menus['editor/title'];
    assert.equal(titleActions.length, 1);
    assert.equal(titleActions[0].command, 'aitrace.explain');
    checks.push('Editor top-right toolbar contains only one AITrace action');
    fs.mkdirSync(path.dirname(report), { recursive: true });
    fs.writeFileSync(report, JSON.stringify({ passed: true, vscode: vscode.version, checks }, null, 2));
  } catch (error) {
    fs.mkdirSync(path.dirname(report), { recursive: true });
    fs.writeFileSync(report, JSON.stringify({ passed: false, checks, error: error.stack }, null, 2));
    throw error;
  }
};
