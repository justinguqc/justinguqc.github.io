const assert = require('assert/strict');
const { Review } = require('../src/review');
const review = new Review('todo');
assert.equal(review.code('result'), review.code('original'));
assert.equal(review.snapshot().total, 3);
assert.equal(review.decide('pending-filter', 'accepted'), true);
const layout = review.fileDocument();
assert.equal(layout.text, review.code('result'));
const countRange = layout.ranges.find(item => item.id === 'pending-count');
assert.equal(layout.text.slice(countRange.start, countRange.end), 'remaining = len(tasks)\n');
assert.match(review.code('result'), /if not task\["completed"\]/);
assert.match(review.code('result'), /remaining = len\(tasks\)/);
assert.equal(review.decide('pending-count', 'accepted'), true);
assert.equal(review.decide('sort-tasks', 'rejected'), true);
assert.match(review.code('result'), /remaining = len\(pending\)/);
assert.doesNotMatch(review.code('result'), /sorted\(/);
assert.equal(review.snapshot().reviewed, 3);
assert.equal(review.undo(), true);
assert.equal(review.states['sort-tasks'], 'pending');
assert.equal(review.decide('sort-tasks', 'accepted'), true);
assert.match(review.code('result'), /sorted\(/);
assert.equal(review.undo(), true);
assert.doesNotMatch(review.code('result'), /sorted\(/);
assert.equal(review.decide('does-not-exist', 'accepted'), false);
review.reset();
assert.equal(review.code('result'), review.code('original'));
assert.equal(review.snapshot().reviewed, 0);
assert.equal(review.snapshot().canUndo, false);
const rendered = review.reviewDocument();
assert.equal(rendered.ranges.length, 3);
for (const item of rendered.ranges) {
  const lines = rendered.text.split('\n').slice(item.start, item.end + 1);
  assert(lines[0].startsWith('@@ Change'));
  assert(lines.some(line => line.startsWith('-')));
  assert(lines.some(line => line.startsWith('+')));
}
const practice = new Review('practice');
practice.decide('pass-check', 'accepted');
assert.match(practice.code('result'), /score >= 60/);
console.log('PASS: decisions, rejection, undo, reset, result code, diff ranges and the 60 boundary.');
